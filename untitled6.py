def evaluate_model(model, dataloader, social_features=None, k=10, device='cuda' if torch.cuda.is_available() else 'cpu'):
    model.eval()
    model.to(device)
    preds, targets = [], []

    with torch.no_grad():
        for seq, target, *social_idx in dataloader:
            seq = seq.to(device)
            target = target.squeeze().to(device)

            if social_features is not None:
                social_idx = social_idx[0].squeeze().to(device)
                social_vec = social_features[social_idx].to(device)
                logits = model(seq, social_vec)
            else:
                logits = model(seq)

            top_k = torch.topk(logits, k=k, dim=1).indices.tolist()
            preds.extend(top_k)
            targets.extend(target.tolist())

    recall = recall_at_k(preds, targets, k)
    ndcg = ndcg_at_k(preds, targets, k)
    return recall, ndcg

