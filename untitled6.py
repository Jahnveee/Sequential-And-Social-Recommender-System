# ✅ Evaluation Function
def evaluate_model(model, test_df, k=10):
    model.eval()
    eval_dataset = EvaluationDataset(test_df, max_seq_len=MAX_SEQ_LEN)
    eval_loader = DataLoader(eval_dataset, batch_size=64, num_workers=2, pin_memory=True)

    recall_total, ndcg_total = 0.0, 0.0
    count = 0

    with torch.no_grad():
        for seqs, targets in tqdm(eval_loader):
            seqs = seqs.to(device)
            targets = targets.to(device).squeeze()

            logits = model(seqs)  # (batch_size, num_items + 1)
            topk_preds = torch.topk(logits, k=k, dim=1).indices  # (batch_size, k)

            for i in range(seqs.size(0)):
                true_item = targets[i].item()
                predicted = topk_preds[i].tolist()

                # Recall@k
                if true_item in predicted:
                    recall_total += 1

                # NDCG@k
                relevance = [1 if item == true_item else 0 for item in predicted]
                ndcg_total += ndcg_score([relevance], [list(range(1, k + 1))])

                count += 1

    recall_at_k = recall_total / count
    ndcg_at_k = ndcg_total / count

    print(f"📈 Recall@{k}: {recall_at_k:.4f}")
    print(f"📈 NDCG@{k}: {ndcg_at_k:.4f}")

