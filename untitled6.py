    input_tensor = torch.LongTensor(mapped_seq).unsqueeze(0).to(device)

    with torch.no_grad():
        logits = model(input_tensor)
        topk = torch.topk(logits, k=top_k, dim=1).indices.squeeze().tolist()

    return [reverse_id_map[idx] for idx in topk if idx in reverse_id_map]

