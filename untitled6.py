import numpy as np

def recall_at_k(preds, targets, k):
    """Computes Recall@K"""
    recall = 0.0
    for p, t in zip(preds, targets):
        recall += int(t in p[:k])
    return recall / len(preds)

def ndcg_at_k(preds, targets, k):
    """Computes NDCG@K"""
    ndcg = 0.0
    for p, t in zip(preds, targets):
        if t in p[:k]:
            idx = p.index(t)
            ndcg += 1 / np.log2(idx + 2)
    return ndcg / len(preds)

