import torch.nn as nn

class SocialTransformerRecModel(nn.Module):
    def __init__(self, num_items, social_dim=1, d_model=128, nhead=4, num_layers=2, max_seq_len=20):
        super().__init__()
        self.item_emb = nn.Embedding(num_items + 1, d_model, padding_idx=0)
        self.pos_emb = nn.Embedding(max_seq_len, d_model)
        self.social_proj = nn.Linear(social_dim, d_model)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.out = nn.Linear(d_model, num_items + 1)

    def forward(self, seq, social_vec):
        pos = torch.arange(seq.size(1), device=seq.device).unsqueeze(0)
        x = self.item_emb(seq) + self.pos_emb(pos)
        social_embed = self.social_proj(social_vec).unsqueeze(1)
        x = x + social_embed  # broadcast across sequence
        x = self.transformer(x.transpose(0, 1))  # Transformer expects (seq_len, batch, dim)
        x = x[-1]  # use last token
        logits = self.out(x)
        return logits

