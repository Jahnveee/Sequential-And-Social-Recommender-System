# ✅ DATASET CLASS
class SequentialRecDataset(Dataset):
    def __init__(self, df, max_seq_len=20):
        self.user_sessions = []
        self.targets = []
        self.max_seq_len = max_seq_len

        for session_id, group in df.groupby("SessionID"):
            items = group["MappedMovieID"].tolist()
            if len(items) < 2:
                continue
            for i in range(1, len(items)):
                seq = items[:i]
                target = items[i]
                seq = ([0] * (max_seq_len - len(seq)) + seq)[-max_seq_len:]
                self.user_sessions.append(seq)
                self.targets.append(target)

    def __len__(self):
        return len(self.user_sessions)

    def __getitem__(self, idx):
        return torch.LongTensor(self.user_sessions[idx]), torch.LongTensor([self.targets[idx]])



class SessionEncoder(nn.Module):
    def __init__(self, num_items, embed_dim=64, hidden_dim=64):
        super().__init__()
        self.item_emb = nn.Embedding(num_items + 1, embed_dim, padding_idx=0)
        self.gru = nn.GRU(embed_dim, hidden_dim, batch_first=True)

    def forward(self, seq):
        x = self.item_emb(seq)  # (B, L, E)
        _, h_n = self.gru(x)    # (1, B, H)
        return h_n.squeeze(0)   # (B, H)

class UserEncoder(nn.Module):
    def __init__(self, num_items, d_model=64, max_seq_len=20):
        super().__init__()
        self.item_emb = nn.Embedding(num_items + 1, d_model, padding_idx=0)
        self.pos_emb = nn.Embedding(max_seq_len, d_model)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=2)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=1)

    def forward(self, seq):
        pos = torch.arange(seq.size(1), device=seq.device).unsqueeze(0).expand_as(seq)
        x = self.item_emb(seq) + self.pos_emb(pos)
        x = self.transformer(x.transpose(0, 1))  # (L, B, D)
        return x[-1]  # (B, D)

class DualEncoderRecModel(nn.Module):
    def __init__(self, num_items, hidden_dim=64, fusion='mlp'):
        super().__init__()
        self.session_encoder = SessionEncoder(num_items, hidden_dim, hidden_dim)
        self.user_encoder = UserEncoder(num_items, hidden_dim)
        self.fusion = fusion
        if fusion == 'mlp':
            self.fuse = nn.Sequential(
                nn.Linear(2 * hidden_dim, hidden_dim),
                nn.ReLU(),
                nn.Linear(hidden_dim, num_items + 1)
            )
        elif fusion == 'attention':
            self.attn = nn.MultiheadAttention(embed_dim=hidden_dim, num_heads=2, batch_first=True)
            self.out = nn.Linear(hidden_dim, num_items + 1)

    def forward(self, session_seq, user_seq=None):
        session_vec = self.session_encoder(session_seq)
        if user_seq is None:
            return self._predict_from(session_vec)

        user_vec = self.user_encoder(user_seq)

        if self.fusion == 'mlp':
            x = torch.cat([session_vec, user_vec], dim=-1)
            return self.fuse(x)
        elif self.fusion == 'attention':
            combined = torch.stack([session_vec, user_vec], dim=1)  # (B, 2, D)
            attn_output, _ = self.attn(combined, combined, combined)
            return self.out(attn_output[:, 0])

    def _predict_from(self, session_vec):
        return self.fuse(torch.cat([session_vec, torch.zeros_like(session_vec)], dim=-1))

# ✅ MODEL CLASS
class TransformerRecModel(nn.Module):
    def __init__(self, num_items, d_model=64, nhead=2, num_layers=1, max_seq_len=20):
        super().__init__()
        self.item_emb = nn.Embedding(num_items + 1, d_model, padding_idx=0)
        self.pos_emb = nn.Embedding(max_seq_len, d_model)
        encoder_layer = nn.TransformerEncoderLayer(d_model=d_model, nhead=nhead)
        self.transformer = nn.TransformerEncoder(encoder_layer, num_layers=num_layers)
        self.out = nn.Linear(d_model, num_items + 1)

    def forward(self, seq):
        positions = torch.arange(seq.size(1), device=seq.device).unsqueeze(0).expand_as(seq)
        x = self.item_emb(seq) + self.pos_emb(positions)
        x = self.transformer(x.transpose(0, 1))  # (seq_len, batch, d_model)
        x = x[-1]  # Use last hidden state
        logits = self.out(x)
        return logits

# ✅ TRAINING FUNCTION
def train_model(model, train_loader, num_epochs=20, lr=0.001):
    model.to(device)
    optimizer = torch.optim.Adam(model.parameters(), lr=lr)
    criterion = nn.CrossEntropyLoss()

    for epoch in range(num_epochs):
        model.train()
        total_loss = 0
        for seq, target in tqdm(train_loader):
            seq, target = seq.to(device), target.to(device).squeeze()
            optimizer.zero_grad()
            logits = model(seq)
            loss = criterion(logits, target)
            loss.backward()
            optimizer.step()
            total_loss += loss.item()
        print(f"Epoch {epoch+1}/{num_epochs} - Loss: {total_loss:.4f}")

