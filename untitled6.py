def recommend_next(model, session_items, id_map, max_seq_len=20, top_k=5):
    model.eval()
    reverse_id_map = {v: k for k, v in id_map.items()}

    # Prepare sequence
    mapped_seq = [id_map[item] for item in session_items if item in id_map]
